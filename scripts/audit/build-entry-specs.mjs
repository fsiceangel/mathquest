import { readFileSync, writeFileSync } from 'node:fs'
import { createServer } from 'vite'
import { numericChoice } from './lib/numeric-choice.mjs'

// Run only after candidate suitability reviews. The product uses the resulting
// explicit manifest, never a heuristic based on the current answer key.
const selectedIds = new Set(JSON.parse(readFileSync('notes/audits/section-entry-selection.json', 'utf8')))
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' })
const groups = []
try {
  const { allChapters, loadVariants } = await server.ssrLoadModule('/src/data/content.js')
  const chapters = allChapters()
  await Promise.all(chapters.map(ch => loadVariants(ch.book, ch.number)))
  for (const ch of chapters) for (const group of [...ch.sections.map(s=>({id:s.id,title:s.title,problems:s.problems})),{id:'challenge',title:'Chapter challenge',problems:ch.challenge}]) {
    const id = `${ch.book}/${ch.number}/${group.id}`
    groups.push({id,title:group.title,total:group.problems.length, selected:group.problems.flatMap((p,index)=>selectedIds.has(`${id}/${index+1}`)? [{index,versions:[p,...p.variants]}] : [])})
  }
} finally { await server.close() }
const manifest = {}, coverage = []
for (const group of groups) {
  const chosen = group.selected
  let converted = 0
  for (const slot of chosen) {
    const specs = slot.versions.map(v => {
      const spec = numericChoice(v.choices[v.answer])
      if (!spec) throw new Error(`Cannot safely parse reviewed choice: ${v.calibration.id}`)
      if (/as (?:a |an )?(?:improper )?fraction|to an improper fraction|simplify.*\\frac/i.test(v.q)) {
        spec.form = 'fraction'
        if (/simplest|lowest terms|simplify/i.test(v.q)) spec.reduced = true
      }
      return spec
    })
    manifest[`${group.id}/${slot.index+1}`] = specs
    converted++
  }
  coverage.push({id:group.id,title:group.title,total:group.total,fillIn:converted,versions:converted*4,
    ...(converted<2 ? {note:'Other slots include non-scalar answers, option-dependent prompts, approximation ambiguity, or incompatible alternate versions; retained as choices.'} : {})})
}
writeFileSync('src/data/section-answer-entry.js', '// Reviewed section/challenge entry specs by stable slot ID; four versions per slot.\n// Generated by scripts/audit/build-entry-specs.mjs after per-book suitability review.\nexport const sectionAnswerEntries = {\n'+Object.entries(manifest).map(([id,specs])=>`  ${JSON.stringify(id)}: ${JSON.stringify(specs)},`).join('\n')+'\n}\n')
const books = Object.fromEntries(['prealgebra','intro-algebra','intro-counting','intro-geometry'].map(book=> {
  const gs=coverage.filter(g=>g.id.startsWith(book+'/')), ss=gs.filter(g=>!g.id.endsWith('/challenge'))
  return [book,{sections:ss.length,sectionsWithFillIn:ss.filter(g=>g.fillIn>0).length,sectionsWithAtLeastTwo:ss.filter(g=>g.fillIn>=2).length,slots:gs.reduce((n,g)=>n+g.fillIn,0),versions:gs.reduce((n,g)=>n+g.versions,0)}]
}))
writeFileSync('notes/audits/section-entry-coverage.json',JSON.stringify({books,groups:coverage},null,2)+'\n')
console.log(JSON.stringify(books,null,2))
